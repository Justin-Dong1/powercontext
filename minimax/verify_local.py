"""Actual seekdb + PowerContext integration. MiniMax is an explicit local protocol fixture."""

from pathlib import Path
import argparse, hashlib, json, os, shutil, socket, subprocess, sys, tempfile, threading, time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import pymysql

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent if HERE.parent.name == "ecosystem" else HERE.parent
FIXTURE_CODE = '"""Status filter protocol fixture; NOT generated by MiniMax."""\ndef list_tickets(tickets, status=None):\n    return [dict(ticket) for ticket in tickets if status is None or ticket.get("status") == status]\n'


class Handler(BaseHTTPRequestHandler):
    requests = []

    def do_POST(self):
        payload = json.loads(self.rfile.read(int(self.headers["Content-Length"])))
        self.requests.append(payload)
        result = {
            "id": "mock-not-minimax",
            "model": "protocol-fixture",
            "stop_reason": "end_turn",
            "usage": {"input_tokens": 0, "output_tokens": 0},
            "content": [
                {
                    "type": "text",
                    "text": json.dumps({"files": {"tickets.py": FIXTURE_CODE}}),
                }
            ],
        }
        raw = json.dumps(result).encode()
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.end_headers()
        self.wfile.write(raw)

    def log_message(self, *args):
        pass


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        "--binary",
        type=Path,
        default=ROOT
        / ".cache/seekdb-lifecycle/node_modules/@oceanbase/seekdb-node-win32-x64/native/seekdb.exe",
    )
    p.add_argument(
        "--powercontext-source",
        type=Path,
        default=ROOT
        / ".cache/minimax-deps/powercontext-fda256c329c6ea9f6e6bb037354922f0f577ac5e/src",
    )
    args = p.parse_args()
    base = ROOT / ".cache/minimax-validation"
    base.mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix="run-", dir=base))
    project = work / "project"
    shutil.copytree(HERE / "sample", project)
    report = {
        "passed": False,
        "actual_minimax": False,
        "scope": "real database, real Memory, mocked HTTP generation; not official submission evidence",
        "directory": str(work),
        "source_sha256": hashlib.sha256(
            (HERE / "sdd_context.py").read_bytes()
        ).hexdigest(),
        "binary": str(args.binary),
        "binary_sha256": hashlib.sha256(args.binary.read_bytes()).hexdigest(),
        "checks": [],
    }
    env = os.environ.copy()
    env["PYTHONPATH"] = str(args.powercontext_source.resolve())
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        port = s.getsockname()[1]
    env.update(
        SEEKDB_HOST="127.0.0.1",
        SEEKDB_PORT=str(port),
        SEEKDB_DATABASE="minimax_sdd",
        SEEKDB_PASSWORD="",
    )
    data = work / "server"
    data.mkdir()
    model = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    threading.Thread(target=model.serve_forever, daemon=True).start()
    process = None
    report["port"] = port

    def check(name, condition):
        report["checks"].append(dict(check=name, passed=bool(condition)))
        print(json.dumps(report["checks"][-1]), flush=True)
        if not condition:
            raise AssertionError(name)

    def call(command, *extra):
        argv = [
            sys.executable,
            str(HERE / "sdd_context.py"),
            "--project",
            str(project),
            "--state",
            str(work / "state.db"),
            "--out",
            str(work / "evidence"),
            command,
            *extra,
        ]
        r = subprocess.run(
            argv,
            env=env,
            cwd=HERE,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            timeout=180,
            text=True,
            encoding="utf8",
            errors="replace",
        )
        if r.returncode:
            raise RuntimeError(r.stdout[-6000:])
        return json.loads(r.stdout.strip().splitlines()[-1])

    try:
        with (work / "server.log").open("w", encoding="utf8") as log:
            process = subprocess.Popen(
                [
                    str(args.binary.resolve()),
                    "--nodaemon",
                    "--base-dir",
                    str(data),
                    "--port",
                    str(port),
                    "--parameter",
                    "memory_budget=1G",
                    "--parameter",
                    "log_disk_size=2G",
                    "--parameter",
                    "datafile_size=32M",
                    "--parameter",
                    "mysql_port_mode=specified",
                    "--parameter",
                    "mysql_port=" + str(port),
                    "--log-level",
                    "WARN",
                ],
                cwd=data,
                stdout=log,
                stderr=subprocess.STDOUT,
                creationflags=subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0,
            )
            deadline = time.monotonic() + 180
            while time.monotonic() < deadline:
                if process.poll() is not None:
                    raise RuntimeError(
                        "seekdb exited: "
                        + str(process.returncode)
                        + "; "
                        + str(work / "server.log")
                    )
                try:
                    conn = pymysql.connect(
                        host="127.0.0.1",
                        port=port,
                        user="root",
                        connect_timeout=2,
                        read_timeout=3,
                    )
                    conn.close()
                    break
                except pymysql.Error:
                    time.sleep(1)
            else:
                raise TimeoutError("Database startup timed out")
            indexed = call("index")
            check("Four real documents indexed in seekdb", indexed["sources"] == 4)
            first = call("context")
            check(
                "Necessary specs code and tests retrieved by actual SQL",
                len(first["sources"]) == 4
                and first["database_queries"]
                and first["checkpoint"]["state"] is None,
            )
            changed = project / "specs/status.md"
            changed.write_text(
                changed.read_text(encoding="utf8")
                + "\nS-5: status filtering revision proof zxcontext2026.\n",
                encoding="utf8",
            )
            call("index")
            updated = call("context")
            check(
                "Reimport uses updated specification, not a fixed answer",
                any("zxcontext2026" in x["content"] for x in updated["sources"])
                and first["revision"] != updated["revision"],
            )
            result = call(
                "develop",
                "--model",
                "protocol-fixture",
                "--allow-mock",
                "--endpoint",
                "http://127.0.0.1:" + str(model.server_address[1]) + "/v1/messages",
            )
            check(
                "Baseline target assertions fail before change",
                result["target_before"]["exit_code"] != 0
                and "FAIL:" in result["target_before"]["output"],
            )
            check(
                "Identical target tests pass after change",
                result["target_after"]["exit_code"] == 0,
            )
            check(
                "Regression tests pass before and after",
                result["regression_before"]["exit_code"]
                == result["regression_after"]["exit_code"]
                == 0,
            )
            check(
                "Tests and specifications were not edited",
                result["protected_sources_unchanged"],
            )
            check(
                "Model request contains actual retrieved sources",
                len(Handler.requests) == 1
                and "zxcontext2026" in Handler.requests[0]["messages"][0]["content"],
            )
            resumed = call("resume")
            check(
                "PowerContext state survives a new CLI process",
                resumed["checkpoint"]["state"]["status"] == "mock_validated"
                and resumed["checkpoint"]["state"]["code_revision"]
                == result["code_revision_after"],
            )
            check(
                "Recovered state is used in next context",
                resumed["next_action"].startswith("Reuse prior"),
            )
            check(
                "Mock generation cannot be misreported as real MiniMax",
                not result["actual_minimax"]
                and not resumed["checkpoint"]["state"]["actual_minimax"],
            )
            # A distinct project must not retrieve another project's sources or state.
            manifest_path = project / "context.json"
            manifest = json.loads(manifest_path.read_text(encoding="utf8"))
            manifest["project"] = "separate-project"
            manifest_path.write_text(json.dumps(manifest), encoding="utf8")
            call("index")
            isolated = call("context")
            check(
                "Project task state is isolated",
                isolated["checkpoint"]["state"] is None,
            )
            report["evidence_directory"] = str(work / "evidence")
            report["passed"] = True
    except Exception as error:
        report["error"] = str(error)
        raise
    finally:
        if process and process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=15)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait()
        model.shutdown()
        model.server_close()
        dest = ROOT / "results/minimax"
        dest.mkdir(parents=True, exist_ok=True)
        (dest / "local-integration.json").write_text(
            json.dumps(report, ensure_ascii=False, indent=2), encoding="utf8"
        )
    print(
        json.dumps(
            dict(
                passed=True,
                checks=len(report["checks"]),
                report=str(dest / "local-integration.json"),
            )
        )
    )


if __name__ == "__main__":
    main()
